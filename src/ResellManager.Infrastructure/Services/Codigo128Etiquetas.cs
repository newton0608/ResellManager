    internal static IReadOnlyList<int> Simbolos(string codigo)
    {
        if(codigo.Length is <1 or >100 || codigo.Any(c=>c<' '||c>'~'))throw new ArgumentException("El código no puede codificarse con Code 128 B.");
        var datos=new List<int>{104}; var suma=104;
        for(var i=0;i<codigo.Length;i++){var valor=codigo[i]-32;datos.Add(valor);suma+=valor*(i+1);}
        datos.Add(suma%103);datos.Add(106);return datos;
    }
    internal static int[] Anchuras(string codigo)=>Simbolos(codigo).SelectMany(s=>Patrones[s].Select(c=>c-'0')).ToArray();
    internal static decimal AnchoMinimo(string codigo,PerfilEtiquetas perfil)=>(Anchuras(codigo).Sum()+20)*2*25.4m/perfil.Dpi+2*perfil.MargenMm;
